def test_clean_refuses_without_tty(tmp_path: Path, monkeypatch, capsys) -> None:
    monkeypatch.chdir(tmp_path)
    stale = tmp_path / "workspace" / "kickoff-stale"
    stale.mkdir(parents=True)
    old = time.time() - 8 * 86400
    os.utime(stale, (old, old))
    monkeypatch.setattr(kickoff, "_open_tty", lambda: None)
    assert kickoff.cmd_kickoff(_parse("--clean", "7d")) == 2
    captured = capsys.readouterr()
    assert "non-interactive" in (captured.out + captured.err).lower()
    assert stale.exists()


def test_restore_swaps_env_bak_back(tmp_path: Path, monkeypatch) -> None:
    monkeypatch.setattr(kickoff, "harness_root", lambda: tmp_path)
    (tmp_path / ".env.bak").write_text("KEY=from-bak\n", encoding="utf-8")
    assert kickoff.cmd_kickoff(_parse("--restore")) == 0
    assert (tmp_path / ".env").read_text(encoding="utf-8") == "KEY=from-bak\n"
    assert not (tmp_path / ".env.bak").exists()


def test_restore_without_bak_fails_cleanly(tmp_path: Path, monkeypatch, capsys) -> None:
    monkeypatch.setattr(kickoff, "harness_root", lambda: tmp_path)
    assert kickoff.cmd_kickoff(_parse("--restore")) == 1
    assert "no" in capsys.readouterr().err.lower()


def test_missing_config_exits_2_without_tty(tmp_path: Path, monkeypatch, capsys) -> None:
    """A non-interactive run with invalid config prints the problems and
    exits 2 instead of creating a kickoff dir."""
    monkeypatch.chdir(tmp_path)
    monkeypatch.setattr(kickoff, "harness_root", lambda: tmp_path)  # no .env here
    monkeypatch.setattr(kickoff, "_open_tty", lambda: None)
    monkeypatch.delenv("CLK_PROVIDER", raising=False)
    rc = kickoff.cmd_kickoff(_parse("--provider", "hal9000", "--no-tui", "idea"))
    assert rc == 2
    err = capsys.readouterr().err
    assert "missing or invalid configuration" in err
    assert "not recognised" in err
    assert not (tmp_path / "workspace").exists()
