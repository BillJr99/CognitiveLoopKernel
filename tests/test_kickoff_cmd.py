def _cfg(**over: str) -> dict:
    base = {"CLK_PROVIDER": "shell", "CLK_MAX_ITERATIONS": "10",
            "CLK_PROJECT_NAME": "clk-app", "CLK_RUN_INSTALL": "false",
            "CLK_NO_TUI": "false", "CLK_AUTH_MODE": "cli"}
    base.update(over)
    return base


def test_missing_config_ok_for_shell() -> None:
    assert kickoff._missing_config(_cfg(), {}, "an idea") == []


def test_missing_config_claude_apikey_requires_key() -> None:
    problems = kickoff._missing_config(
        _cfg(CLK_PROVIDER="claude", CLK_AUTH_MODE="apikey"), {}, "idea")
    assert any("ANTHROPIC_API_KEY" in p for p in problems)
    assert kickoff._missing_config(
        _cfg(CLK_PROVIDER="claude", CLK_AUTH_MODE="apikey"),
        {"ANTHROPIC_API_KEY": "sk"}, "idea") == []
    # cli auth mode never requires the key.
    assert kickoff._missing_config(_cfg(CLK_PROVIDER="claude"), {}, "idea") == []


def test_missing_config_gemini_accepts_google_key() -> None:
    cfg = _cfg(CLK_PROVIDER="gemini", CLK_AUTH_MODE="apikey")
    assert kickoff._missing_config(cfg, {"GOOGLE_API_KEY": "g"}, "idea") == []
    assert kickoff._missing_config(cfg, {}, "idea")


def test_missing_config_openwebui_requires_endpoint_and_model() -> None:
    problems = kickoff._missing_config(_cfg(CLK_PROVIDER="openwebui"), {}, "idea")
    assert any("CLK_OPENWEBUI_ENDPOINT" in p for p in problems)
    assert any("CLK_OPENWEBUI_MODEL" in p for p in problems)


def test_missing_config_rejects_unknown_provider_and_bad_iterations() -> None:
    problems = kickoff._missing_config(
        _cfg(CLK_PROVIDER="hal9000", CLK_MAX_ITERATIONS="lots"), {}, "idea")
    assert any("not recognised" in p for p in problems)
    assert any("CLK_MAX_ITERATIONS" in p for p in problems)


def test_missing_config_no_tui_requires_idea() -> None:
    problems = kickoff._missing_config(_cfg(CLK_NO_TUI="true"), {}, "")
    assert any("idea argument is required" in p for p in problems)
    assert kickoff._missing_config(_cfg(CLK_NO_TUI="true"), {}, "an idea") == []


