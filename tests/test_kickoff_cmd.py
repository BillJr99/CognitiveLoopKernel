@pytest.mark.parametrize("case", sorted(CONFIG_CASES))
def test_config_env_overrides_match_shell_heredoc(tmp_path: Path, case: str) -> None:
    cfg_path = tmp_path / "clk.config.json"
    shutil.copy(GOLDEN / "base_clk_config.json", cfg_path)
    apply_config_env_overrides(cfg_path, env=CONFIG_CASES[case])
    expected = (GOLDEN / f"config_{case}.json").read_text(encoding="utf-8")
    assert cfg_path.read_text(encoding="utf-8") == expected


@pytest.mark.parametrize("case", sorted(PROVIDER_CASES))
def test_provider_activation_matches_shell_heredoc(tmp_path: Path, case: str) -> None:
    prov_path = tmp_path / "providers.json"
    shutil.copy(GOLDEN / "base_providers.json", prov_path)
    activate_provider(prov_path, env=PROVIDER_CASES[case])
    expected = (GOLDEN / f"providers_{case}.json").read_text(encoding="utf-8")
    assert prov_path.read_text(encoding="utf-8") == expected


def test_config_overrides_noop_when_file_missing(tmp_path: Path) -> None:
    """`if not p.exists(): raise SystemExit(0)` in the heredoc == no-op."""
    missing = tmp_path / "clk.config.json"
    apply_config_env_overrides(missing, env=CONFIG_CASES["full_valid"])
    assert not missing.exists()


def test_config_overrides_preserve_unrelated_keys(tmp_path: Path) -> None:
    cfg_path = tmp_path / "clk.config.json"
    cfg_path.write_text(json.dumps({"custom": {"x": 1}, "robustness": {"keep": True}}),
                        encoding="utf-8")
    apply_config_env_overrides(cfg_path, env={"CLK_ROBUSTNESS_MAX_QA_DEPTH": "5"})
    out = json.loads(cfg_path.read_text(encoding="utf-8"))
    assert out["custom"] == {"x": 1}
    assert out["robustness"] == {"keep": True, "max_qa_depth": 5}


# ---------------------------------------------------------------------------
# Cast helpers (the heredoc's _bool/_csv semantics)
# ---------------------------------------------------------------------------


def test_bool_cast_semantics() -> None:
    for truthy in ("1", "true", "TRUE", " Yes ", "y", "on", "ON"):
        assert _bool(truthy) is True, truthy
    for falsy in ("0", "false", "no", "n", "off", "", "garbage", "2"):
        assert _bool(falsy) is False, falsy


def test_csv_cast_semantics() -> None:
    assert _csv("  a , ,b ,,c  ") == ["a", "b", "c"]
    assert _csv("solo") == ["solo"]
    assert _csv(" , ,, ") == []
    assert _csv("") == []


