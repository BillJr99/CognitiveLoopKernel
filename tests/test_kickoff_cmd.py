def _parse(*argv: str) -> argparse.Namespace:
    return build_parser().parse_args(["kickoff", *argv])


def test_parser_mirrors_kickoff_sh_flags() -> None:
    ns = _parse("--setup", "--restore", "--list", "--clean", "7d",
                "--provider", "shell", "--max-iterations", "3",
                "--project-name", "p", "--no-tui", "--run-install", "my idea")
    assert ns.setup and ns.restore and ns.list_mode
    assert ns.clean == "7d"
    assert ns.provider == "shell"
    assert ns.max_iterations == "3"
    assert ns.project_name == "p"
    assert ns.no_tui_override == "true"
    assert ns.run_install is True
    assert ns.idea == "my idea"
    assert ns.func is kickoff.cmd_kickoff


def test_parser_tui_flag_wins_when_last() -> None:
    assert _parse("--no-tui", "--tui").no_tui_override == "false"
    assert _parse("--tui", "--no-tui").no_tui_override == "true"
    assert _parse().no_tui_override is None


def test_list_without_workspace(tmp_path: Path, monkeypatch, capsys) -> None:
    monkeypatch.chdir(tmp_path)
    assert kickoff.cmd_kickoff(_parse("--list")) == 0
    assert "no workspace" in capsys.readouterr().out.lower()


def test_list_shows_kickoff_dirs(tmp_path: Path, monkeypatch, capsys) -> None:
    monkeypatch.chdir(tmp_path)
    (tmp_path / "workspace" / "kickoff-20260101-120000").mkdir(parents=True)
    state = tmp_path / "workspace" / "kickoff-20260201-120000" / ".clk" / "state"
    state.mkdir(parents=True)
    (state / "idea.json").write_text(json.dumps({"title": "A grand idea"}), encoding="utf-8")
    assert kickoff.cmd_kickoff(_parse("--list")) == 0
    out = capsys.readouterr().out
    assert "kickoff-20260101-120000" in out
    assert "kickoff-20260201-120000" in out
    assert "A grand idea" in out


